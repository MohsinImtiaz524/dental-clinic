import { test, expect } from "@playwright/test";
import { db } from "../../lib/db";
import { hashPassword } from "../../lib/password";
import { clinicDateKey } from "../../lib/clinic-time";

test.beforeAll(async () => {
  await db.prescriptionItem.deleteMany();
  await db.prescription.deleteMany();
  await db.treatmentRecord.deleteMany();
  await db.consultation.deleteMany();
  await db.appointment.deleteMany();
  await db.patient.deleteMany();
  await db.user.deleteMany();
  await db.rateLimit.deleteMany();
  await db.user.create({ data: { name: "Dashboard Administrator", email: "dashboard@example.test", passwordHash: await hashPassword("Dashboard secure passphrase!") } });
});
test.afterAll(async () => { await db.prescriptionItem.deleteMany(); await db.prescription.deleteMany(); await db.treatmentRecord.deleteMany(); await db.consultation.deleteMany(); await db.appointment.deleteMany(); await db.patient.deleteMany(); await db.$disconnect(); });

test("empty states, navigation, patient registration, booking, and live dashboard figures", async ({ page }) => {
  for (const route of ["/patients", "/appointments", "/profile", "/patients/new", "/appointments/new"]) {
    await page.goto(route);
    await expect(page).toHaveURL(/\/login$/);
  }
  await page.getByLabel("Email address").fill("dashboard@example.test");
  await page.getByLabel("Password", { exact: true }).fill("Dashboard secure passphrase!");
  await page.getByRole("button", { name: "Sign in to workspace" }).click();
  await expect(page.getByRole("heading", { name: "Welcome, Dashboard Administrator." })).toBeVisible();
  for (const metric of ["Total patients", "Today's appointments", "Scheduled today", "Completed today"]) {
    await expect(page.getByTestId(`metric-${metric}`)).toHaveText("0");
  }
  await expect(page.getByText("A little room in your day", { exact: true })).toBeVisible();
  await expect(page.getByText("Your first patient starts here", { exact: true })).toBeVisible();
  const navigation = page.getByRole("navigation", { name: "Main navigation", exact: true });
  await navigation.getByRole("link", { name: "Appointments", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Appointments", exact: true })).toBeVisible();
  await expect(page.getByText("No appointments on this day")).toBeVisible();
  await page.getByRole("link", { name: "Book appointment", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Add a patient first" })).toBeVisible();
  await navigation.getByRole("link", { name: "Patients", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Patients", exact: true })).toBeVisible();
  await expect(page.getByText("No patients yet", { exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Add patient", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Add a patient" })).toBeVisible();
  await page.getByLabel("Full name", { exact: true }).fill("Dashboard Test Patient");
  await page.getByLabel("Phone number", { exact: false }).fill("+92 300 1234567");
  await page.getByRole("button", { name: "Save patient", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Dashboard Test Patient", exact: true })).toBeVisible();
  await db.patient.create({ data: { name: "Search Decoy", phone: "+92 311 9999999" } });
  await page.goto("/appointments/new");
  await expect(page.getByRole("heading", { name: "Book an appointment", exact: true })).toBeVisible();
  const patientSearch = page.getByRole("combobox", { name: "Patient", exact: true });
  await patientSearch.fill("1234567");
  await expect(page.getByRole("option", { name: /Dashboard Test Patient/ })).toBeVisible();
  await expect(page.getByRole("option", { name: /Search Decoy/ })).not.toBeVisible();
  await page.screenshot({ path: ".local/patient-search-dropdown.png", fullPage: true });
  await patientSearch.press("ArrowDown");
  await patientSearch.press("Enter");
  await expect(patientSearch).toHaveValue("Dashboard Test Patient");
  await page.getByLabel("Date and time", { exact: true }).fill(`${clinicDateKey()}T10:30`);
  await page.getByLabel("Appointment reason").fill("General consultation");
  await page.getByRole("button", { name: "Book appointment", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Appointments", exact: true })).toBeVisible();
  await expect(page.getByRole("cell", { name: "General consultation" })).toBeVisible();
  await page.getByRole("link", { name: "Book appointment", exact: true }).click();
  const conflictPatient = page.getByRole("combobox", { name: "Patient", exact: true });
  await conflictPatient.fill("Search Decoy");
  await conflictPatient.press("ArrowDown");
  await conflictPatient.press("Enter");
  await page.getByLabel("Date and time", { exact: true }).fill(`${clinicDateKey()}T10:45`);
  await page.getByLabel("Duration").selectOption("30");
  await page.getByLabel("Appointment reason").fill("Overlapping consultation");
  await page.getByRole("button", { name: "Book appointment", exact: true }).click();
  await expect(page.getByRole("alert")).toContainText("Scheduling conflict");
  expect(await db.appointment.count()).toBe(1);
  await page.getByLabel("I understand and want to continue.").check();
  await page.getByRole("button", { name: "Confirm booking", exact: true }).click();
  await expect(page.getByRole("cell", { name: "Overlapping consultation" })).toBeVisible();
  const overlapping = await db.appointment.findFirstOrThrow({ where: { reason: "Overlapping consultation" } });
  await page.goto(`/appointments/${overlapping.id}/edit`);
  await expect(page.getByRole("heading", { name: "Reschedule appointment" })).toBeVisible();
  await page.getByLabel("Date and time", { exact: true }).fill(`${clinicDateKey()}T11:30`);
  await page.getByLabel("Duration").selectOption("45");
  await page.getByRole("button", { name: "Save new time" }).click();
  const rescheduled = await db.appointment.findUniqueOrThrow({ where: { id: overlapping.id } });
  expect(rescheduled.durationMinutes).toBe(45);
  const cancelledRow = page.getByRole("row").filter({ hasText: "Overlapping consultation" });
  await cancelledRow.getByLabel("Appointment status").selectOption("CANCELLED");
  await cancelledRow.getByRole("button", { name: "Save", exact: true }).click();
  await expect(cancelledRow.getByText("Cancelled", { exact: true })).toBeVisible();
  expect(await db.appointment.count({ where: { id: overlapping.id, status: "CANCELLED" } })).toBe(1);
  await page.getByRole("link", { name: "Week", exact: true }).click();
  await expect(page.getByRole("grid", { name: "Weekly appointment calendar" })).toBeVisible();
  await expect(page.getByRole("grid", { name: "Weekly appointment calendar" }).getByText("Overlapping consultation")).toBeVisible();
  await page.goto("/patients/new");
  await page.getByLabel("Full name", { exact: true }).fill("  TEST   USER  ");
  await page.getByLabel("Phone number", { exact: false }).fill("+92 300 1234567");
  await page.getByRole("button", { name: "Save patient", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("already exists");
  const patientCount = await db.patient.count();
  expect(patientCount).toBe(2);
  expect(await db.appointment.count()).toBe(2);
  await navigation.getByRole("link", { name: "Dashboard", exact: true }).click();
  await expect(page.getByTestId("metric-Total patients")).toHaveText(String(patientCount));
  await expect(page.getByTestId("metric-Today's appointments")).toHaveText("2");
  await expect(page.getByTestId("metric-Scheduled today")).toHaveText("1");
  await expect(page.getByTestId("metric-Completed today")).toHaveText("0");
  await expect(page.getByRole("region", { name: "Recent patients" }).getByRole("link", { name: /Dashboard Test Patient/ })).toBeVisible();
  await navigation.getByRole("link", { name: "Appointments", exact: true }).click();
  const generalRow = page.getByRole("row").filter({ hasText: "General consultation" });
  await expect(generalRow.getByLabel("Appointment status")).toBeVisible();
  await generalRow.getByLabel("Appointment status").selectOption("COMPLETED");
  await generalRow.getByRole("button", { name: "Save", exact: true }).click();
  await expect(generalRow.getByText("Completed", { exact: true })).toBeVisible();
  await navigation.getByRole("link", { name: "Dashboard", exact: true }).click();
  await expect(page.getByTestId("metric-Scheduled today")).toHaveText("0");
  await expect(page.getByTestId("metric-Completed today")).toHaveText("1");

  for (const width of [1440, 1024, 768]) {
    await page.setViewportSize({ width, height: 1000 });
    await expect(page.getByRole("heading", { name: "Today's appointments", exact: false })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: `.local/dashboard-${width}.png`, fullPage: true });
  }
  await navigation.getByRole("link", { name: "My account", exact: true }).click();
  await expect(page.getByRole("heading", { name: "My account", exact: true })).toBeVisible();
  await expect(page.getByText("dashboard@example.test")).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole("button", { name: "Open navigation", exact: true }).click();
  await page.getByRole("navigation", { name: "Mobile navigation", exact: true }).getByRole("link", { name: "Dashboard", exact: true }).click();
  await expect(page.getByTestId("metric-Total patients")).toHaveText("2");
  await expect(page.getByRole("navigation", { name: "Mobile navigation", exact: true })).not.toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
